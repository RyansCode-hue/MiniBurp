#!/usr/bin/env bash
# Clean-build the MiniBurp.app bundle.
#
# Always does a fully clean build: wipes build/ + dist/ AND passes --clean
# to PyInstaller so its own cache is dropped. The alternative is silently
# launching stale bytecode from a previous build — which is exactly the
# bug this script exists to prevent.
#
# Usage:
#   ./build.sh          # clean rebuild
#   ./build.sh --run    # rebuild then launch dist/MiniBurp.app

set -euo pipefail
cd "$(dirname "$0")"

RUN=0
case "${1:-}" in
  ""|--clean) ;;
  --run)      RUN=1 ;;
  -h|--help)
    sed -n '2,/^[^#]/p' "$0" | sed 's/^# \{0,1\}//;$d'
    exit 0 ;;
  *)
    echo "unknown argument: $1" >&2
    exit 2 ;;
esac

# Prefer the project venv. Fall back to system python3 with a warning, so
# fresh clones still work but the canonical path is the venv.
if [[ -x .venv/bin/python ]]; then
  PYTHON=.venv/bin/python
else
  PYTHON=$(command -v python3 || true)
  if [[ -z $PYTHON ]]; then
    echo "no python3 found; create .venv first (see README)" >&2
    exit 1
  fi
  echo "warning: no .venv/ — using $PYTHON" >&2
fi

if ! "$PYTHON" -m PyInstaller --version >/dev/null 2>&1; then
  echo "installing pyinstaller into $PYTHON …"
  "$PYTHON" -m pip install --quiet pyinstaller
fi

echo "wiping build/ + dist/ …"
rm -rf build dist

# Stamp the bundle with build metadata so the runtime check in
# miniburp/_build_check.py can spot a stale .app launched against an
# updated source tree. The hash uses the same algorithm as the runtime
# check, so re-running build.sh with no source changes is a no-op for it.
echo "writing miniburp/_build_info.py …"
"$PYTHON" - <<'PY'
import datetime
import subprocess
from pathlib import Path

from miniburp._build_check import compute_source_hash

repo = Path(".").resolve()
try:
    sha = subprocess.check_output(
        ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL,
    ).strip()
except (OSError, subprocess.CalledProcessError):
    sha = "unknown"

build_time = datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
src_hash = compute_source_hash(repo)

(repo / "miniburp" / "_build_info.py").write_text(
    '"""Auto-generated by build.sh. Do not edit; do not commit."""\n'
    f"BUILD_SHA = {sha!r}\n"
    f"BUILD_TIME = {build_time!r}\n"
    f"BUILD_SOURCE_HASH = {src_hash!r}\n"
)
print(f"  build_sha={sha[:7]} hash={src_hash[:12]}…")
PY

echo "running pyinstaller …"
"$PYTHON" -m PyInstaller miniburp.spec --clean --noconfirm

bundle=dist/MiniBurp.app
if [[ ! -d $bundle ]]; then
  echo "build finished but $bundle is missing — check pyinstaller output above" >&2
  exit 1
fi

size=$(du -sh "$bundle" | cut -f1)
git_sha=$(git rev-parse --short HEAD 2>/dev/null || echo "unknown")

echo
echo "✓ built $bundle ($size)"
echo "  source revision: $git_sha"

if (( RUN )); then
  echo
  echo "launching $bundle …"
  open "$bundle"
fi
