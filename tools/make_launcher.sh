#!/usr/bin/env bash
# Build a STABLE launcher MiniBurp.app that runs the live source tree.
#
# Why this exists: `./build.sh` re-freezes the app with PyInstaller every time,
# producing a new code-signing identity on each build. macOS keys per-app grants
# (Accessibility, firewall, …) to that identity, so every rebuild re-prompts.
#
# This launcher is a tiny wrapper bundle whose executable just runs
# `<repo>/.venv/bin/python run.py`. It contains no frozen bootloader and no
# argv-emulation (the thing that triggered the Accessibility prompt), and its
# bytes never change — so its identity is stable forever. Updating MiniBurp
# becomes `git pull`; you never rebuild this bundle (only re-run this script if
# you move the repo or change the icon).
#
# Usage:
#   tools/make_launcher.sh          # build/refresh ~/Applications/MiniBurp.app
#   tools/make_launcher.sh --open   # build then launch it

set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
APP="${HOME}/Applications/MiniBurp.app"

OPEN=0
case "${1:-}" in
  "") ;;
  --open) OPEN=1 ;;
  -h|--help) sed -n '2,/^set -euo/p' "$0" | sed 's/^# \{0,1\}//;$d'; exit 0 ;;
  *) echo "unknown argument: $1" >&2; exit 2 ;;
esac

# Sanity: the launcher is useless without the venv + entry point it points at.
if [[ ! -x "$REPO/.venv/bin/python" ]]; then
  echo "no $REPO/.venv/bin/python — create the venv first (see README)" >&2
  exit 1
fi
if [[ ! -f "$REPO/run.py" ]]; then
  echo "no $REPO/run.py — is $REPO the MiniBurp repo?" >&2
  exit 1
fi

echo "building launcher → $APP"
echo "  pointing at repo: $REPO"

mkdir -p "${HOME}/Applications"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# --- Info.plist ---
# CFBundleIdentifier matches the PyInstaller bundle id so the QSettings domain
# (com.miniburp.MiniBurp) and any existing prefs carry over unchanged.
cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>MiniBurp</string>
  <key>CFBundleDisplayName</key><string>MiniBurp</string>
  <key>CFBundleIdentifier</key><string>com.miniburp.app</string>
  <key>CFBundleExecutable</key><string>MiniBurp</string>
  <key>CFBundleIconFile</key><string>MiniBurp.icns</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.2.0</string>
  <key>CFBundleVersion</key><string>0.2.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

# --- executable launcher ---
# REPO is baked in literally (expanded now); $REPO / $@ stay literal for runtime.
cat > "$APP/Contents/MacOS/MiniBurp" <<EOF
#!/bin/bash
# Auto-generated by tools/make_launcher.sh — runs MiniBurp from live source.
REPO="$REPO"
cd "\$REPO" || exit 1
exec "\$REPO/.venv/bin/python" run.py "\$@"
EOF
chmod 755 "$APP/Contents/MacOS/MiniBurp"

# --- icon ---
if [[ -f "$REPO/assets/MiniBurp.icns" ]]; then
  cp "$REPO/assets/MiniBurp.icns" "$APP/Contents/Resources/MiniBurp.icns"
else
  echo "warning: assets/MiniBurp.icns missing — app will use a generic icon" >&2
fi

# --- stable identity ---
# Clear any quarantine flag and ad-hoc sign once. Because the bundle never
# changes again, this signature is stable across every future `git pull`.
xattr -cr "$APP" 2>/dev/null || true
codesign --force --deep --sign - "$APP" >/dev/null 2>&1 || \
  echo "warning: codesign failed (app will still run)" >&2

echo
echo "✓ installed $APP"
echo "  update MiniBurp from now on with:  git -C \"$REPO\" pull"
echo "  (no rebuild; the app always runs the checked-out source)"

# A leftover frozen build shares the bundle id and confuses Spotlight/Dock
# (two "MiniBurp" entries). Point it out so the user can clear it.
if [[ -d "$REPO/dist/MiniBurp.app" ]]; then
  echo
  echo "⚠ a frozen build still exists at $REPO/dist/MiniBurp.app"
  echo "  two 'MiniBurp' apps share bundle id com.miniburp.app and confuse"
  echo "  Spotlight/Dock. Remove the old one:  rm -rf \"$REPO/dist\""
fi

if (( OPEN )); then
  echo "launching …"
  open "$APP"
fi
